def tell_key(e):
    if e.street == 0:
        return None
    g = 1 if e.street == 3 else 0
    if e.act == "check" and e.sit[:8] == "p_no_bet":
        return (g, "x")
    if e.act != "raise":
        return None
    if e.sit[:8] != "p_no_bet":
        return (g, "r")
    k = 0
    for edge in EDGES:
        if e.frac >= edge:
            k += 1
    return (g, k)

